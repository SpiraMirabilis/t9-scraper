// Builds the in-page code for a site: one self-contained async function
//   async ({ name, arg }) => result
// assembled from makeCommon() + the adapter's makeSite(common) via toString().
//
// Both engines run this same source:
//  * patchright evaluates it directly (isolated world, or main when the
//    adapter's `worlds` map says so);
//  * the extension can't eval (MV3), so scripts/build-inpage.js writes it to
//    extension/inpage/<site>.js, where it is registered under a one-shot
//    global that the invoker deletes after use.
//
// Nothing persists in the page between calls. Names prefixed "common." hit
// the shared helpers (e.g. "common.isChallenged"); the rest hit the site.
import { makeCommon } from './sites/common.js';

export const invokerSource = (adapter) => `async ({ name, arg }) => {
  const makeCommon = ${makeCommon.toString()};
  const makeSite = ${adapter.makeSite.toString()};
  const common = makeCommon();
  const target = name.startsWith('common.') ? common : makeSite(common);
  const fn = target[name.replace(/^common\\./, '')];
  if (typeof fn !== 'function') throw new Error('no in-page method ' + name);
  return await fn.call(target, arg);
}`;

// The file form for the extension. executeScript({files}) runs it, then a
// static func calls and deletes the global.
export const extensionFileSource = (adapter) =>
  `// Generated by scripts/build-inpage.js from src/sites/${adapter.name}.js -- do not edit.\n` +
  `globalThis.__scrInvoke = ${invokerSource(adapter)};\n`;

export const worldFor = (adapter, name) =>
  (name.startsWith('common.') ? 'isolated' : (adapter.worlds?.[name] || 'isolated'));
